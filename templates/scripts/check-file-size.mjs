// Потолок размера файла для всех платформ монорепо: веб, бэкенд, iOS, Android.
//
// Файл длиннее 500 строк кода значит одно из двух: в нём две подсистемы или
// инвентарь. И то, и другое режется, а не терпится. Комментарии и пустые строки
// не считаются: они несут причины, и штрафовать за них значило бы их вырезать.
//
// У каждой платформы есть свой линтер с похожим правилом (eslint max-lines,
// SwiftLint file_length, detekt LargeClass), но у каждого свой способ считать и
// свои дыры. Этот скрипт считает одинаково везде и стоит в /gate.
//
// Исключения перечислены ниже, каждое со своей причиной. Поднять порог ради
// одного файла нельзя: либо файл режется, либо попадает сюда с причиной.
//
// Запуск: node scripts/check-file-size.mjs. Код выхода 1 при нарушении.
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MAX_LINES = 500;
const EXTENSIONS = new Set(['.ts', '.tsx', '.mts', '.js', '.mjs', '.swift', '.kt', '.kts']);

/** Что не проверяется, и почему. */
const EXCEPTIONS = [
  // Тесты читаются сценарием целиком, резать их по порогу значит рвать сценарий.
  { pattern: /\.test\.(ts|tsx|mts)$/, reason: 'tests' },
  { pattern: /Tests?\.swift$/, reason: 'tests' },
  { pattern: /\/src\/(test|androidTest)\//, reason: 'tests' },
  // Сгенерированное правится генератором, а не рукой.
  { pattern: /\/migrations\//, reason: 'generated migrations' },
  { pattern: /\.gen\.(ts|swift|kt)$/, reason: 'generated code' },
  { pattern: /(^|\/)next-env\.d\.ts$/, reason: 'generated by Next' },
];

function listFiles() {
  // Только то, что git видит: node_modules, build и прочее из .gitignore отпадают сами.
  const out = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard'], {
    cwd: ROOT,
    encoding: 'utf8',
  });
  return out.split('\n').filter((file) => file && EXTENSIONS.has(path.extname(file)));
}

/** Строки кода: без пустых и без строк, где только комментарий. */
export function countCodeLines(source) {
  let inBlock = false;
  let count = 0;
  for (const raw of source.split('\n')) {
    let line = raw.trim();
    if (inBlock) {
      const end = line.indexOf('*/');
      if (end === -1) continue;
      inBlock = false;
      line = line.slice(end + 2).trim();
    }
    while (line.startsWith('/*')) {
      const end = line.indexOf('*/', 2);
      if (end === -1) {
        inBlock = true;
        line = '';
        break;
      }
      line = line.slice(end + 2).trim();
    }
    if (line === '' || line.startsWith('//')) continue;
    count++;
  }
  return count;
}

const violations = [];
for (const file of listFiles()) {
  const rel = `/${file}`;
  if (EXCEPTIONS.some((e) => e.pattern.test(rel))) continue;
  let source;
  try {
    source = readFileSync(path.join(ROOT, file), 'utf8');
  } catch {
    continue; // файл удалён, но ещё в индексе
  }
  const lines = countCodeLines(source);
  if (lines > MAX_LINES) violations.push({ file, lines });
}

if (violations.length === 0) {
  console.log(`file-size: every file is within ${MAX_LINES} code lines`);
} else {
  for (const v of violations.sort((a, b) => b.lines - a.lines)) {
    console.error(`file-size: ${v.file} has ${v.lines} code lines (max ${MAX_LINES}). Split it.`);
  }
  process.exit(1);
}
